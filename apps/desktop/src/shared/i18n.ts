export function stringsFor(lang: Lang): Strings {
	return lang === "tr" ? tr : en;
}

export function pickLanguage(locale: string | null | undefined): Lang {
	// kalem-locale-ok: language codes are ASCII
	return locale?.toLowerCase().startsWith("tr") === true ? "tr" : "en";
}

/** Fills `{0}`, `{1}` placeholders. */
export function format(text: string, ...values: readonly (string | number)[]): string {
	return text.replace(/\{(\d+)\}/g, (raw, n: string) => {
		const value = values[Number(n)];
		return value === undefined ? raw : String(value);
	});
}
